-- Normalize legacy mixed-case order statuses to uppercase Figure 20 Order State Machine (without NEGOTIATING)
UPDATE orders
SET status = CASE
  WHEN UPPER(TRIM(status)) IN ('DRAFT', 'WAITING_FOR_DOCUMENTS', 'PENDING_DOCUMENTS', 'NEGOTIATING') THEN 'DRAFT'
  WHEN UPPER(TRIM(status)) = 'CONFIRMED' THEN 'CONFIRMED'
  WHEN UPPER(TRIM(status)) = 'READY_FOR_PLANNING' THEN 'READY_FOR_PLANNING'
  WHEN UPPER(TRIM(status)) IN ('ASSIGNED', 'PLANNED', 'DISPATCHED') THEN 'ASSIGNED'
  WHEN UPPER(TRIM(status)) = 'ACCEPTED' THEN 'ACCEPTED'
  WHEN UPPER(TRIM(status)) IN ('PICKED UP', 'PICKED_UP') THEN 'PICKED_UP'
  WHEN UPPER(TRIM(status)) IN ('IN TRANSIT', 'IN_TRANSIT', 'IN PROGRESS', 'IN_PROGRESS') THEN 'IN_TRANSIT'
  WHEN UPPER(TRIM(status)) IN ('HANDED_OVER_VENDOR', 'HANDED_OVER_TO_VENDOR', 'HANDED OVER TO VENDOR') THEN 'HANDED_OVER_VENDOR'
  WHEN UPPER(TRIM(status)) = 'DELIVERED' THEN 'DELIVERED'
  WHEN UPPER(TRIM(status)) IN ('DELIVERED (EXCEPTION)', 'DELIVERED_EXCEPTION', 'DELIVERED EXCEPTION') THEN 'DELIVERED_EXCEPTION'
  WHEN UPPER(TRIM(status)) IN ('CANCELLED', 'CANCELED') THEN 'CANCELLED'
  WHEN UPPER(TRIM(status)) = 'CLOSED' THEN 'CLOSED'
  ELSE UPPER(REPLACE(TRIM(status), ' ', '_'))
END,
is_closed = CASE
  WHEN UPPER(TRIM(status)) = 'CLOSED' THEN TRUE
  WHEN UPPER(TRIM(status)) IN ('HANDED_OVER_VENDOR', 'HANDED_OVER_TO_VENDOR', 'HANDED OVER TO VENDOR') THEN FALSE
  ELSE COALESCE(is_closed, FALSE)
END
WHERE status IS NOT NULL;
